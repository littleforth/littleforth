#!/usr/bin/env python3
"""svd2forth.py SVD OUTDIR CHIP [PERIPHERALS [LICENCE]] - one Forth file of
register addresses per peripheral. PERIPHERALS, comma-separated, keeps those
of a family SVD that the chip has; LICENCE is written when the SVD has none.

Each file holds CONSTANTs: the peripheral base, then PERIPH.REGISTER for every
register (clusters as PERIPH.CLUSTER.REGISTER). An array (PIN_CNF[32] and the
like) gets one constant for element 0; the comment gives the count and step,
so element n is  n step * BASE + .  The SVD's licence text is kept in every
file, as BSD-3-Clause requires. Load only the files a program needs: each
constant costs about 36 bytes of dictionary.
Names over 31 characters (the dictionary limit): the peripheral prefix is
dropped, then only the last 31 characters are kept; a name that still clashes
inside its file is written commented out, with a note. Every line is cut to
127 characters (only comments lose their tail): the kernel reads 128.
"""
import os, re, sys, xml.etree.ElementTree as ET

MAXNAME = 31
MAXLINE = 127

def num(t):
    return int(t, 0) if t else 0

def clean(n):
    return re.sub(r"\[%s\]|%s", "", n)

def walk(node, base, prefix, out):
    """registers and clusters under node, offsets relative to base"""
    for el in node:
        tag = el.tag
        if tag not in ("register", "cluster"):
            continue
        name = clean(el.findtext("name"))
        off = base + num(el.findtext("addressOffset"))
        dim, step = num(el.findtext("dim")), num(el.findtext("dimIncrement"))
        note = f"[{dim}] step {step}" if dim else ""
        if tag == "register":
            out.append((prefix + name, off, note, el.findtext("description") or ""))
        else:
            walk(el, off, prefix + name + ".", out)
            if note:
                out.append((prefix + name, off, note + " (cluster)", ""))

def main():
    svd, outdir, chip = sys.argv[1], sys.argv[2], sys.argv[3]
    dev = ET.parse(svd).getroot()
    lic = (dev.findtext("licenseText") or (sys.argv[5] if len(sys.argv) > 5 else "")).strip().splitlines()
    per = {p.findtext("name"): p for p in dev.iter("peripheral")}
    only = sys.argv[4].split(",") if len(sys.argv) > 4 and sys.argv[4] else None
    os.makedirs(outdir, exist_ok=True)
    total, long_names, files, clashes = 0, [], [], []
    for pname, p in sorted(per.items()):
        if only and pname not in only:
            continue
        src = per[p.get("derivedFrom")] if p.get("derivedFrom") else p
        root = p
        while root.findtext("groupName") is None and root.get("derivedFrom"):
            root = per[root.get("derivedFrom")]
        ptype = root.findtext("groupName") or re.sub(r"\d+$", "", root.findtext("name"))
        base = num(p.findtext("baseAddress"))
        regs = []
        rnode = src.find("registers")
        if rnode is not None:
            walk(rnode, 0, "", regs)
        lines = [f"\\ {pname}.fth - {chip} {pname} register addresses.",
                 f"\\ Generated by tools/svd2forth.py from {os.path.basename(svd)}; do not edit.",
                 "\\"] + ["\\ " + l.strip() for l in lic] + ["",
                 f"\\ type: {ptype}", f"${base:08X} CONSTANT {pname}"]
        seen = set()
        for rname, off, note, desc in sorted(regs, key=lambda r: r[1]):
            name = f"{pname}.{rname}"
            if len(name) > MAXNAME:
                long_names.append(name)
                name = rname if len(rname) <= MAXNAME else rname[-MAXNAME:]
                note = (note + "  " if note else "") + f"full name {pname}.{rname}"
            comment = ("\\ " + note + "  " if note else "\\ ") + re.sub(r"\s+", " ", desc)[:60]
            line = f"${base + off:08X} CONSTANT {name:31} {comment}".rstrip()[:MAXLINE].rstrip()
            if name.upper() in seen:
                clashes.append(f"{pname}.{rname}")
                line = "\\ " + line + "  (name clash: not defined)"
            seen.add(name.upper())
            lines.append(line)
            total += 1
        open(os.path.join(outdir, pname + ".fth"), "w").write("\n".join(lines) + "\n")
        files.append((pname, len(regs)))
    print(f"svd2forth: {len(files)} peripherals, {total} registers -> {outdir}")
    if long_names:
        print(f"  {len(long_names)} names over {MAXNAME} characters shortened; {len(clashes)} left undefined after a clash"
              + (": " + ", ".join(clashes) if clashes else ""))

if __name__ == "__main__":
    main()
